package com.skyisland.craft;

/**
 * 配方分类（PRD 5.6.2 的"分类"列）。
 *
 * <p>它现在只有两个用途：让配方表与 PRD 逐列对齐，以及给将来的合成界面提供
 * "按分类分组显示"的依据。之所以现在就建立它而不是留个字符串：
 * PRD 的分类列是一个<b>封闭集合</b>，用枚举表达可以让"PRD 新增了一个分类"
 * 变成编译期错误，而不是一个谁都不会发现的拼写差异。
 */
public enum RecipeCategory {

    /** 建材（木板 / 木棍 / 火把 / 玻璃 / 木门 …）。 */
    BUILD,

    /** 材料（铁锭 / 铜锭 / 火药 …）。 */
    MATERIAL,

    /** 弹药（手枪弹 / 步枪弹 / 霰弹）。 */
    AMMO,

    /** 枪械。 */
    GUN,

    /** 食物（面包 / 急救包）。 */
    FOOD
}
